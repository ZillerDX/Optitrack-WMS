import { NextRequest, NextResponse } from 'next/server';
import { supabaseRest, getAuthUser } from '@/lib/supabase';
import { rateLimit } from '@/lib/rateLimit';
import { analyzeProduct, DataUnavailableError, loadWarehouse, stockByProduct, unitsSoldByProduct } from '@/lib/aiData';

export const dynamic = 'force-dynamic';

export async function GET(req: NextRequest) {
  try {
    const user = await getAuthUser(req);
    if (!user) {
      return NextResponse.json({ detail: 'Unauthorized' }, { status: 401 });
    }

    const limited = await rateLimit(req, {
      name: 'ai-predictive',
      limit: 60,
      windowSeconds: 60,
      identifier: { value: String(user.id), limit: 20, windowSeconds: 60 },
    });
    if (limited) return limited;

    // 1. One shared, checked read of the warehouse (a failed read is a 503, never "empty")
    const now = new Date();
    const { products, inventory, outbound, locations: allLocations } = await loadWarehouse(user.id, now);
    const poRes = await supabaseRest(`purchase_orders?user_id=eq.${user.id}&order=created_at.desc&limit=50`);
    if (!poRes.ok) throw new DataUnavailableError('purchase orders');
    const existingPOs = await poRes.json();

    // 2-3. Stock over all locations and 30-day velocity, the same numbers the chat and the report use
    const stock = stockByProduct(inventory);
    const sold = unitsSoldByProduct(outbound, now);

    // 4. Build predictive models for each product
    const items: any[] = [];
    const draftPOs: any[] = [];

    for (const prod of [...products].sort((x, y) => String(x.name).localeCompare(String(y.name)))) {
      const pId = prod.id;
      // Where it is stored now; a product with no stock row goes to the tenant's first location
      // (a name that really exists, unlike the hardcoded one this used to suggest), or null if there is none
      const targetLocation = stock.get(pId)?.locations[0] ?? allLocations[0]?.name ?? null;
      const costPrice = Number(prod.cost_price) || 0;
      const sellPrice = Number(prod.sell_price) || 0;
      const supplier = prod.supplier || 'Primary Supplier';

      const a = analyzeProduct(prod, stock.get(pId)?.quantity ?? 0, sold.get(pId) ?? 0);
      const { urgency, current_stock: currentStock, min_stock_level: minStock, daily_burn_rate: dailyBurnRate } = a;
      const daysOfInventory = a.days_of_inventory ?? (currentStock < minStock ? 7 : 999);
      let estimatedRunoutDate: string;
      if (currentStock <= 0) estimatedRunoutDate = 'Depleted';
      else if (a.days_of_inventory !== null) {
        estimatedRunoutDate = new Date(now.getTime() + a.days_of_inventory * 24 * 60 * 60 * 1000).toISOString().split('T')[0];
      } else estimatedRunoutDate = currentStock < minStock ? 'Low Movement' : 'Stable (>90 days)';
      const recommendedQty = a.suggested_reorder_qty;

      items.push({
        product_id: pId,
        sku: prod.sku,
        name: prod.name,
        category: prod.category || 'General',
        supplier,
        target_location: targetLocation,
        current_stock: currentStock,
        min_stock_level: minStock,
        cost_price: costPrice,
        sell_price: sellPrice,
        units_sold_30d: a.units_sold_30d,
        daily_burn_rate: dailyBurnRate,
        days_of_inventory: daysOfInventory,
        estimated_runout_date: estimatedRunoutDate,
        suggested_reorder_qty: recommendedQty,
        urgency,
      });

      // Generate a Draft Purchase Order if item needs restocking
      if (urgency === 'CRITICAL' || urgency === 'WARNING') {
        const totalCost = Number((recommendedQty * costPrice).toFixed(2));
        draftPOs.push({
          id: `DRAFT-${pId}-${Date.now().toString().slice(-4)}`,
          // A label for the draft only: the real, unique PO number is made by the server on approval
          po_number: `DRAFT-${new Date().toISOString().slice(0, 10).replace(/-/g, '')}-${String(prod.sku).replace(/[^a-zA-Z0-9]/g, '')}`,
          product_id: pId,
          product_name: prod.name,
          sku: prod.sku,
          supplier,
          target_location: targetLocation,
          current_stock: currentStock,
          reorder_qty: recommendedQty,
          unit_cost: costPrice,
          total_amount: totalCost,
          urgency,
          days_remaining: daysOfInventory,
          estimated_lead_days: 3,
          notes: `Auto-generated by AI Agent: ${urgency === 'CRITICAL' ? 'Stockout impending' : 'Below safety threshold'} (${currentStock}/${minStock} pcs, ${dailyBurnRate} pcs/day velocity).`,
        });
      }
    }

    // 5. Aggregate Macro Metrics
    const totalCritical = items.filter((i) => i.urgency === 'CRITICAL').length;
    const totalWarning = items.filter((i) => i.urgency === 'WARNING').length;
    const totalHealthy = items.filter((i) => i.urgency === 'HEALTHY').length;
    const totalEstRestockBudget = draftPOs.reduce((sum, po) => sum + po.total_amount, 0);

    return NextResponse.json({
      summary: {
        total_tracked_products: items.length,
        critical_count: totalCritical,
        warning_count: totalWarning,
        healthy_count: totalHealthy,
        draft_po_count: draftPOs.length,
        total_restock_budget: Number(totalEstRestockBudget.toFixed(2)),
      },
      predictive_items: items,
      draft_purchase_orders: draftPOs,
      approved_purchase_orders: Array.isArray(existingPOs) ? existingPOs : [],
    });
  } catch (err: any) {
    if (err instanceof DataUnavailableError) {
      return NextResponse.json({ detail: 'Warehouse data is temporarily unavailable. Please try again shortly.' }, { status: 503 });
    }
    console.error('[Predictive API Error]:', err);
    return NextResponse.json({ detail: 'Failed to build the reorder analysis' }, { status: 500 });
  }
}
